 "use client";
import { useState } from "react";
import Link from "next/link";

export default function AdminQC() {
  const [qcOrderNo, setQcOrderNo] = useState("QC-8829");
  const [rawNotes, setRawNotes] = useState("");
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedReport, setGeneratedReport] = useState("");

  const handleGenerateAIReport = (e: React.FormEvent) => {
    e.preventDefault();
    setIsGenerating(true);
    setTimeout(() => {
      setGeneratedReport(`========================================\n       SWIFT-LINE INSPECTION REPORT      \n========================================\nOrder ID: ${qcOrderNo}\nDate: ${new Date().toLocaleDateString()}\nStatus: PASSED / APPROVED\n\n[Inspector Notes]:\n${rawNotes}\n\nGenerated by Swiftline AI Engine 🚀`.trim());
      setIsGenerating(false);
    }, 1500);
  };

  return (
    <div className="min-h-screen bg-slate-900 text-slate-200 font-sans flex flex-col md:flex-row">
      {/* Sidebar */}
      <aside className="w-full md:w-72 bg-[#0B1120] border-r border-white/10 p-6 flex flex-col">
        <div className="flex items-center gap-2 mb-10">
          <div className="w-8 h-8 rounded-lg bg-red-600 flex items-center justify-center font-bold text-white shadow-[0_0_15px_rgba(220,38,38,0.5)]">W</div>
          <div className="text-xl font-bold tracking-tight text-white">Swiftline<span className="text-red-500">.</span> WMS</div>
        </div>
        <nav className="space-y-2 flex-1">
          <Link href="/admin" className="flex items-center gap-3 px-4 py-3 rounded-xl text-slate-400 hover:bg-white/5 hover:text-white text-sm font-medium"><span>📟</span> Inbound Scanner</Link>
          <Link href="/admin/consolidation" className="flex items-center gap-3 px-4 py-3 rounded-xl text-slate-400 hover:bg-white/5 hover:text-white text-sm font-medium"><span>📦</span> Consolidation Hub</Link>
          <Link href="/admin/qc" className="flex items-center gap-3 px-4 py-3 rounded-xl bg-white/10 text-white text-sm font-medium"><span>✨</span> Smart AI QC</Link>
        </nav>
        <div className="mt-auto pt-6 border-t border-white/10">
          <Link href="/dashboard" className="w-full flex items-center justify-center gap-2 px-4 py-2 rounded-lg bg-blue-600/20 text-blue-400 hover:bg-blue-600 hover:text-white transition text-sm font-medium">
            👁️ View Client Portal
          </Link>
        </div>
      </aside>

      {/* Main Content */}
      <main className="flex-1 p-8">
        <header className="flex justify-between items-center mb-10 bg-[#0B1120]/80 backdrop-blur-md p-4 rounded-2xl border border-white/10">
          <div>
            <h1 className="text-2xl font-bold text-white">Smart AI QC Report Generator</h1>
            <p className="text-sm text-slate-400">Automated PDF inspection reports</p>
          </div>
          <span className="bg-emerald-500/20 text-emerald-400 px-3 py-1 rounded-full text-xs font-bold border border-emerald-500/30">System Online 🟢</span>
        </header>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
          <div className="bg-[#0B1120] rounded-3xl border border-white/10 p-8 shadow-2xl">
            <h2 className="text-xl font-bold text-white mb-2">Generate Report</h2>
            <p className="text-slate-400 text-sm mb-6">Type rough notes and let AI format it.</p>
            
            <form onSubmit={handleGenerateAIReport} className="space-y-5">
              <div>
                <label className="block text-xs font-bold text-slate-400 uppercase tracking-wider mb-2">Order ID</label>
                <input type="text" value={qcOrderNo} onChange={(e) => setQcOrderNo(e.target.value)} className="w-full bg-black/40 border border-white/10 text-white rounded-xl px-4 py-3 font-mono" required />
              </div>
              <div>
                <label className="block text-xs font-bold text-slate-400 uppercase tracking-wider mb-2">Inspector Notes</label>
                <textarea rows={4} value={rawNotes} onChange={(e) => setRawNotes(e.target.value)} placeholder="e.g. Board working, Tolerance 0.5mm, all good..." className="w-full bg-black/40 border border-white/10 text-white rounded-xl px-4 py-3 focus:outline-none focus:border-purple-500" required></textarea>
              </div>
              <button type="submit" disabled={isGenerating} className="w-full bg-purple-600 hover:bg-purple-500 disabled:bg-slate-700 text-white font-bold py-4 rounded-xl transition shadow-[0_0_20px_rgba(147,51,234,0.4)]">
                {isGenerating ? "🤖 AI Generating Report..." : "✨ Generate Professional PDF Report"}
              </button>
            </form>
          </div>

          <div className="bg-[#0B1120] rounded-3xl border border-white/10 p-8 flex flex-col justify-between shadow-2xl">
            <div>
              <h3 className="text-lg font-bold text-white mb-4">Live Report Preview</h3>
              <div className="bg-black/50 border border-white/10 rounded-2xl p-6 font-mono text-xs text-emerald-400 h-64 overflow-y-auto whitespace-pre-wrap">
                {generatedReport || "// Generated report will appear here..."}
              </div>
            </div>
            <button disabled={!generatedReport} className="mt-6 w-full bg-emerald-600 hover:bg-emerald-500 disabled:bg-slate-800 disabled:text-slate-600 text-white font-bold py-3 rounded-xl transition">
              📥 Publish to Client Dashboard
            </button>
          </div>
        </div>
      </main>
    </div>
  );
}