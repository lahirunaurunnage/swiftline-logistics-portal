"use client";
import { useState, useEffect } from "react";
import { createClient } from "@supabase/supabase-js";
import Link from "next/link";
import { useRouter } from "next/navigation";

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!
);

export default function AdminQCPanel() {
  const router = useRouter();
  const [jobs, setJobs] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  // Report Generator States
  const [generatingJobId, setGeneratingJobId] = useState<string | null>(null);
  const [activeReport, setActiveReport] = useState<{ jobId: string; content: string } | null>(null);
  const [publishing, setPublishing] = useState(false);

  useEffect(() => {
    fetchJobs();
  }, []);

  const fetchJobs = async () => {
    const { data: { user } } = await supabase.auth.getUser();
    if (!user) return router.push("/login");

    const { data: profile } = await supabase.from("profiles").select("role").eq("id", user.id).single();
    if (profile?.role !== "admin") return router.push("/dashboard");

    const { data } = await supabase.from("qc_jobs").select("*").order("created_at", { ascending: false });
    if (data) setJobs(data);
    setLoading(false);
  };

  const handleApprove = async (jobId: string) => {
    const { error } = await supabase.from("qc_jobs").update({ status: "In Progress" }).eq("job_id", jobId);
    if (!error) {
      alert("Job Approved! Inspector can now start working.");
      fetchJobs();
    }
  };

  const handleReject = async (jobId: string) => {
    const { error } = await supabase.from("qc_jobs").update({ status: "Awaiting Inspector", inspector_id: null }).eq("job_id", jobId);
    if (!error) {
      alert("Application Rejected. Job is back on the market.");
      fetchJobs();
    }
  };

  const handleGenerateAIReport = (job: any) => {
    setGeneratingJobId(job.job_id);
    setActiveReport(null);

    // AI API එකට කනෙක්ට් කරනකන්, අපි මෙතන Simulated AI Report එකක් හදනවා
    setTimeout(() => {
      const professionalReportText = `========================================
       SWIFTLINE AI INSPECTION REPORT      
========================================
ORDER ID : ${job.job_id}
PRODUCT  : ${job.product_name}
LOCATION : ${job.location}
DATE     : ${new Date().toLocaleDateString()}
STATUS   : PASSED / APPROVED

[ AI ANALYSIS OF INSPECTOR NOTES ]
${job.special_notes ? job.special_notes.toUpperCase() : "NO NOTES PROVIDED."}

[ QUALITY CHECKS ]
- Packaging integrity: Verified & Secure
- Component count: Matched with invoice
- Visual defects: None detected
- Media Logs: ${job.image_urls?.length || 0} Photos securely stored in Swiftline Vault.

Generated by Swiftline AI Engine 🚀`;

      setActiveReport({ jobId: job.job_id, content: professionalReportText });
      setGeneratingJobId(null);
    }, 1500);
  };

  const handlePublishReport = async (jobId: string) => {
    setPublishing(true);
    const { error } = await supabase
      .from("qc_jobs")
      .update({ status: "Report Ready" })
      .eq("job_id", jobId);

    if (!error) {
      alert("Success! The AI Report has been published to the Client's Dashboard.");
      setActiveReport(null);
      fetchJobs();
    } else {
      alert("Failed to publish report.");
    }
    setPublishing(false);
  };

  const pendingApprovals = jobs.filter(j => j.status === "Pending Admin Approval");
  const awaitingReports = jobs.filter(j => j.status === "Awaiting AI Report");

  return (
    <div className="min-h-screen bg-slate-900 text-slate-200 font-sans flex flex-col md:flex-row">
      {/* ---------------- SIDEBAR ---------------- */}
      <aside className="w-full md:w-72 bg-[#0B1120] border-r border-white/10 p-6 flex flex-col hidden md:flex">
        <div className="flex items-center gap-2 mb-10">
          <div className="w-8 h-8 rounded-lg bg-red-600 flex items-center justify-center font-bold text-white shadow-[0_0_15px_rgba(220,38,38,0.5)]">W</div>
          <div className="text-xl font-bold tracking-tight text-white">Swiftline<span className="text-red-500">.</span> Admin</div>
        </div>
        <nav className="space-y-2 flex-1">
          <Link href="/admin/wms" className="flex items-center gap-3 px-4 py-3 rounded-xl text-slate-400 hover:bg-white/5 hover:text-white text-sm font-medium"><span>📟</span> Inbound Scanner</Link>
          <Link href="/admin/consolidation" className="flex items-center gap-3 px-4 py-3 rounded-xl text-slate-400 hover:bg-white/5 hover:text-white text-sm font-medium"><span>📦</span> Consolidation Hub</Link>
          <Link href="/admin/qc" className="flex items-center gap-3 px-4 py-3 rounded-xl bg-white/10 text-white text-sm font-medium border border-white/10"><span>✨</span> QC Management</Link>
        </nav>
        <div className="mt-auto pt-6 border-t border-white/10">
          <button onClick={async () => { await supabase.auth.signOut(); router.push("/login"); }} className="w-full text-slate-400 hover:text-white text-sm font-medium text-left px-4">Log Out</button>
        </div>
      </aside>

      {/* ---------------- MAIN CONTENT ---------------- */}
      <main className="flex-1 p-6 sm:p-10 overflow-y-auto bg-[#04060d]">
        
        <header className="flex justify-between items-center mb-10 bg-[#0B1120]/80 backdrop-blur-md p-6 rounded-3xl border border-white/10 shadow-xl">
          <div>
            <h1 className="text-2xl sm:text-3xl font-bold text-white">Admin HQ: QC Management 👑</h1>
            <p className="text-sm text-slate-400 mt-1">Manage inspector applications and generate AI reports.</p>
          </div>
          <span className="bg-emerald-500/20 text-emerald-400 px-4 py-1.5 rounded-full text-xs font-bold border border-emerald-500/30 hidden sm:block">System Online 🟢</span>
        </header>

        {loading ? (
          <div className="flex justify-center py-12"><div className="w-8 h-8 border-4 border-purple-500 border-t-transparent rounded-full animate-spin"></div></div>
        ) : (
          <>
            {/* ---------------- SECTION 1: PENDING APPROVALS ---------------- */}
            <div className="mb-12">
              <h2 className="text-xl font-bold text-orange-400 mb-6 flex items-center gap-2">
                <span className="animate-pulse">🔴</span> Action Required: Pending Approvals ({pendingApprovals.length})
              </h2>
              <div className="grid grid-cols-1 gap-4">
                {pendingApprovals.map(job => (
                  <div key={job.job_id} className="bg-orange-900/10 border border-orange-500/30 rounded-3xl p-6 flex flex-col md:flex-row justify-between items-start md:items-center gap-6 shadow-lg shadow-orange-900/10">
                    <div>
                      <span className="bg-orange-500/20 text-orange-400 px-3 py-1 rounded-lg text-xs font-bold mr-3">{job.job_id}</span>
                      <h3 className="text-lg font-bold text-white mt-3">{job.product_name}</h3>
                      <p className="text-sm text-slate-400 mt-1">Inspector wants to take this job.</p>
                    </div>
                    <div className="flex w-full md:w-auto gap-3 mt-4 md:mt-0">
                      <button onClick={() => handleReject(job.job_id)} className="flex-1 md:flex-none bg-red-500/10 hover:bg-red-500/20 text-red-400 font-bold py-3 px-6 rounded-xl transition">Reject</button>
                      <button onClick={() => handleApprove(job.job_id)} className="flex-1 md:flex-none bg-emerald-600 hover:bg-emerald-500 text-white font-bold py-3 px-6 rounded-xl transition shadow-[0_0_15px_rgba(16,185,129,0.4)]">Approve</button>
                    </div>
                  </div>
                ))}
                {pendingApprovals.length === 0 && (
                  <div className="bg-[#0B1120] border border-white/10 p-8 rounded-3xl text-center text-slate-500">No pending approvals.</div>
                )}
              </div>
            </div>

            {/* ---------------- SECTION 2: AI REPORT GENERATOR ---------------- */}
            <div>
              <h2 className="text-xl font-bold text-purple-400 mb-6 flex items-center gap-2">
                <span>🤖</span> Generate AI Reports ({awaitingReports.length})
              </h2>
              
              <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
                
                {/* Job List for Reports */}
                <div className="space-y-6">
                  {awaitingReports.map(job => (
                    <div key={job.job_id} className="bg-[#0B1120] rounded-3xl border border-white/10 p-6 shadow-2xl relative overflow-hidden">
                      <div className="absolute top-0 right-0 w-32 h-32 bg-purple-600/10 rounded-full blur-3xl -z-10"></div>
                      
                      <div className="flex justify-between items-center mb-4">
                        <span className="bg-purple-500/20 text-purple-400 px-3 py-1 rounded-lg text-xs font-bold">{job.job_id}</span>
                        <span className="text-xs font-bold text-slate-400 uppercase">Data Received</span>
                      </div>
                      <h3 className="text-lg font-bold text-white mb-4">{job.product_name}</h3>
                      
                      {/* Real Data From Inspector */}
                      <div className="bg-black/40 border border-white/5 rounded-xl p-4 mb-4">
                        <p className="text-xs text-slate-400 font-bold uppercase mb-2">Inspector Notes:</p>
                        <p className="text-sm text-slate-300 italic">"{job.special_notes}"</p>
                      </div>

                      {/* Render Images if available */}
                      {job.image_urls && job.image_urls.length > 0 && (
                        <div className="mb-6">
                          <p className="text-xs text-slate-400 font-bold uppercase mb-2">Uploaded Photos:</p>
                          <div className="flex gap-3 overflow-x-auto pb-2">
                            {job.image_urls.map((url: string, index: number) => (
                              <img key={index} src={url} alt="QC" className="w-16 h-16 object-cover rounded-lg border border-white/10 shadow-md" />
                            ))}
                          </div>
                        </div>
                      )}

                      <button 
                        onClick={() => handleGenerateAIReport(job)}
                        disabled={generatingJobId === job.job_id} 
                        className="w-full bg-purple-600 hover:bg-purple-500 disabled:bg-slate-700 text-white font-bold py-3 rounded-xl transition shadow-[0_0_15px_rgba(147,51,234,0.4)]"
                      >
                        {generatingJobId === job.job_id ? "🤖 Analyzing Data..." : "✨ Generate AI PDF Report"}
                      </button>
                    </div>
                  ))}
                  {awaitingReports.length === 0 && (
                    <div className="bg-[#0B1120] border border-white/10 p-8 rounded-3xl text-center text-slate-500">No raw data waiting for reports.</div>
                  )}
                </div>

                {/* Live Preview Panel */}
                <div className="bg-[#0B1120] rounded-3xl border border-white/10 p-8 flex flex-col justify-between shadow-2xl sticky top-8 h-fit">
                  <div>
                    <h3 className="text-lg font-bold text-white mb-4">Live Report Preview</h3>
                    <div className="bg-black/50 border border-white/10 rounded-2xl p-6 font-mono text-xs text-emerald-400 h-[400px] overflow-y-auto whitespace-pre-wrap">
                      {activeReport ? activeReport.content : "// Select a job and click Generate to preview the AI Report..."}
                    </div>
                  </div>
                  <button 
                    disabled={!activeReport || publishing} 
                    onClick={() => activeReport && handlePublishReport(activeReport.jobId)}
                    className="mt-6 w-full bg-emerald-600 hover:bg-emerald-500 disabled:bg-slate-800 disabled:text-slate-600 text-white font-bold py-4 rounded-xl transition shadow-[0_0_15px_rgba(16,185,129,0.3)]"
                  >
                    {publishing ? "Publishing..." : "📥 Publish to Client Dashboard"}
                  </button>
                </div>
              </div>
            </div>
            
          </>
        )}
      </main>
    </div>
  );
}